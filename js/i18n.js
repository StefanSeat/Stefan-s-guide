  const SUPPORTED = ["sr", "en"];
  const BALKAN = ["sr", "hr", "bs", "sh", "cnr", "me", "mk", "sl"];

  function initialLang() {
    const q = new URLSearchParams(location.search).get("lang");
    if (SUPPORTED.includes(q)) return q;
    try {
      const s = localStorage.getItem("sv-lang");
      if (SUPPORTED.includes(s)) return s;
    } catch {}
    const nav = (navigator.languages || [navigator.language || ""]).map((x) => String(x).toLowerCase().split("-")[0]);
    return nav.some((x) => BALKAN.includes(x)) ? "sr" : "en";
  }

  let lang = initialLang();

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) ?? DICT.sr[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }

  // Polje objekta na trenutnom jeziku: title -> title_en (ako postoji)
  function pick(obj, field) {
    if (!obj) return "";
    return (lang === "en" && obj[field + "_en"]) || obj[field] || "";
  }

  const catLabel = (key) => t("cat." + key);
  const tag = (x) => (lang === "en" ? TAGS_EN[x] || x : x);

  function apply(root = document) {
    document.documentElement.lang = lang === "en" ? "en" : "sr-Latn";
    document.title = t("meta.title");
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute("content", t("meta.desc"));
    root.querySelectorAll("[data-i18n]").forEach((el) => (el.innerHTML = t(el.dataset.i18n)));
    root.querySelectorAll("[data-i18n-ph]").forEach((el) => el.setAttribute("placeholder", t(el.dataset.i18nPh)));
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
    document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", b.dataset.lang === lang));
  }

  function setLang(l) {
    if (!SUPPORTED.includes(l) || l === lang) return;
    lang = l;
    try { localStorage.setItem("sv-lang", l); } catch {}
    apply();
    document.dispatchEvent(new CustomEvent("sv:lang", { detail: l }));
  }

  window.I18N = { t, pick, catLabel, tag, apply, setLang, get lang() { return lang; } };

  // Prevedi stranicu odmah (skripta se učitava na kraju stranice, posle sadržaja)
  apply();

  document.addEventListener("click", (e) => {
    const b = e.target.closest("[data-lang]");
    if (b) setLang(b.dataset.lang);
  });
